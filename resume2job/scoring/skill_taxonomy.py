def _build_synonym_map() -> dict:
    """构建 alias -> canonical 的小写映射。"""
    mapping = {}
    for group in SYNONYM_GROUPS:
        canonical = group[0].strip().lower()
        for alias in group:
            mapping[alias.strip().lower()] = canonical
    return mapping


